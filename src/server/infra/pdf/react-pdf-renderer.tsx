import "server-only";
import { Document, Page, StyleSheet, Text, View, renderToBuffer } from "@react-pdf/renderer";
import { LABELS } from "@/domain/enums";
import { formatNaira } from "@/domain/money";
import { formatDateOnly, formatDateTime } from "@/lib/dates";
import type { DocumentRenderer } from "@/server/ports/receipt-renderer";
import type { RateRecord, ReceiptSnapshot } from "@/server/ports/repositories";
import type { YearSummary } from "@/domain/year-summary";

// The built-in Helvetica has no ₦ glyph, so PDFs print "NGN".
const money = (kobo: number) => formatNaira(kobo).replace("₦", "NGN ");

const styles = StyleSheet.create({
  page: { padding: 40, fontSize: 11, fontFamily: "Helvetica", color: "#1f2937" },
  header: { borderBottomWidth: 2, borderBottomColor: "#0f766e", paddingBottom: 10, marginBottom: 18 },
  org: { fontSize: 20, fontFamily: "Helvetica-Bold", color: "#0f766e" },
  title: { fontSize: 13, marginTop: 4 },
  row: { flexDirection: "row", paddingVertical: 5, borderBottomWidth: 0.5, borderBottomColor: "#e5e7eb" },
  label: { width: "40%", color: "#6b7280" },
  value: { width: "60%" },
  amountBox: { marginTop: 18, padding: 12, backgroundColor: "#f0fdfa", flexDirection: "row", justifyContent: "space-between" },
  amount: { fontSize: 16, fontFamily: "Helvetica-Bold" },
  note: { marginTop: 24, fontSize: 9, color: "#6b7280" },
  tableHead: { flexDirection: "row", paddingVertical: 6, borderBottomWidth: 1, borderBottomColor: "#0f766e", fontFamily: "Helvetica-Bold" },
  cellWide: { width: "65%" },
  cellNarrow: { width: "35%", textAlign: "right" },
  total: { flexDirection: "row", paddingVertical: 6, fontFamily: "Helvetica-Bold", borderTopWidth: 1, borderTopColor: "#1f2937" },
});

function Field({ label, value }: { label: string; value: string }) {
  return (
    <View style={styles.row}>
      <Text style={styles.label}>{label}</Text>
      <Text style={styles.value}>{value}</Text>
    </View>
  );
}

function ReceiptDocument({ r }: { r: ReceiptSnapshot }) {
  return (
    <Document title={`Receipt ${r.receiptNo}`} author={r.orgName}>
      <Page size="A5" style={styles.page}>
        <View style={styles.header}>
          <Text style={styles.org}>{r.orgName}</Text>
          <Text style={styles.title}>Official payment receipt</Text>
        </View>
        <Field label="Receipt number" value={r.receiptNo} />
        <Field label="Received from" value={r.payerName} />
        <Field label="Payment purpose" value={r.purpose} />
        {r.purpose !== r.categoryName ? <Field label="Category" value={r.categoryName} /> : null}
        {r.coverage.length ? <Field label="Covers" value={r.coverage.join(", ")} /> : null}
        <Field label="Payment date" value={formatDateOnly(r.paidOn)} />
        <Field label="Payment method" value={LABELS.paymentMethod[r.method]} />
        <Field label="Confirmed" value={`${formatDateTime(new Date(r.confirmedAt))} by ${r.confirmedByName}`} />
        {r.replacesReceiptNo ? <Field label="Replaces receipt" value={r.replacesReceiptNo} /> : null}
        <View style={styles.amountBox}>
          <Text>Amount paid</Text>
          <Text style={styles.amount}>{money(r.amountKobo)}</Text>
        </View>
        <Text style={styles.note}>
          This receipt was generated by the {r.orgName} payment system after the payment was confirmed.
        </Text>
      </Page>
    </Document>
  );
}

function YearSummaryDocument({
  orgName,
  summary,
  rates,
  generatedAt,
}: {
  orgName: string;
  summary: YearSummary;
  rates: RateRecord[];
  generatedAt: Date;
}) {
  return (
    <Document title={`${orgName} financial summary ${summary.year}`} author={orgName}>
      <Page size="A4" style={styles.page}>
        <View style={styles.header}>
          <Text style={styles.org}>{orgName}</Text>
          <Text style={styles.title}>Financial summary — {summary.year}</Text>
        </View>
        <View style={styles.tableHead}>
          <Text style={styles.cellWide}>Item</Text>
          <Text style={styles.cellNarrow}>Amount</Text>
        </View>
        <View style={styles.row}>
          <Text style={styles.cellWide}>
            Balance brought forward from {summary.year - 1}
            {summary.broughtForwardRecorded ? "" : " (not yet recorded)"}
          </Text>
          <Text style={styles.cellNarrow}>{money(summary.broughtForwardKobo)}</Text>
        </View>
        {summary.receiptsByCategory.map((c) => (
          <View style={styles.row} key={c.categoryId}>
            <Text style={styles.cellWide}>
              Received: {c.categoryName} ({c.count} payments)
            </Text>
            <Text style={styles.cellNarrow}>{money(c.totalKobo)}</Text>
          </View>
        ))}
        <View style={styles.row}>
          <Text style={styles.cellWide}>Total received (confirmed payments)</Text>
          <Text style={styles.cellNarrow}>{money(summary.totalReceiptsKobo)}</Text>
        </View>
        <View style={styles.total}>
          <Text style={styles.cellWide}>Total funds (brought forward + received)</Text>
          <Text style={styles.cellNarrow}>{money(summary.totalFundsKobo)}</Text>
        </View>
        <View style={[styles.row, { marginTop: 10 }]}>
          <Text style={styles.cellWide}>Outstanding member balances</Text>
          <Text style={styles.cellNarrow}>{money(summary.outstandingKobo)}</Text>
        </View>

        {rates.length ? (
          <View style={{ marginTop: 24 }}>
            <Text style={{ fontFamily: "Helvetica-Bold", marginBottom: 6 }}>Rates set for {summary.year}</Text>
            {rates.map((rate) => (
              <View style={styles.row} key={rate.id}>
                <Text style={styles.cellWide}>
                  {rate.categoryName} ({LABELS.frequency[rate.frequency]})
                </Text>
                <Text style={styles.cellNarrow}>{money(rate.amountKobo)}</Text>
              </View>
            ))}
          </View>
        ) : null}
        <Text style={styles.note}>
          Spending is not recorded in this system. Generated {formatDateTime(generatedAt)}.
        </Text>
      </Page>
    </Document>
  );
}

export const reactPdfRenderer: DocumentRenderer = {
  async receiptPdf(receipt) {
    return new Uint8Array(await renderToBuffer(<ReceiptDocument r={receipt} />));
  },
  async yearSummaryPdf(input) {
    return new Uint8Array(await renderToBuffer(<YearSummaryDocument {...input} />));
  },
};
